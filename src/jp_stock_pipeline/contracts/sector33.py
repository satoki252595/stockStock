"""東証33業種の名称と、EDINET「提出者業種」から D1 `core_stocks.sector33` への正規化。

## なぜ正規化が要るか（2026-09-13 実測）

EDINET コードリスト（`Edinetcode.zip`）の上場企業の「提出者業種」は、
**東証33業種の名称そのもの + `外国法人・組合`（2 社）**だった。表記ゆれは
1 件だけで、EDINET は `倉庫・運輸関連`、東証は `倉庫・運輸関連業`（34 社）。
公開面は東証33業種の名称で絞り込み・表示するので、D1 へ書く直前にここで揃える。

`外国法人・組合` は33業種ではないので None にする（2 社とも本番
`core_stocks` の is_active=1 に居ない）。33 名称以外を素通しすると、
公開面の業種フィルタに存在しない選択肢が 1 件だけ湧く。

## 分類そのものの違いは直さない

JPX 由来の `core_stocks.sector` と名称が一致するのは、表記ゆれ補正後で約 96.2%。
残りは**分類の違い**である（例: JPX `情報・通信業` → EDINET `サービス業` 27 件、
その逆 19 件、`小売業` → `サービス業` 7 件）。EDINET の値は提出者の申告で、
東証が割り当てた業種ではない。ここで JPX 側へ寄せると `sector33` に JPX 由来
（personal-only）の値が混ざり、列単位のライセンス区分が成立しなくなるので寄せない。

## 採らなかった案

- `collectors/edinet_codelist.py` で正規化する: Notion ① とローカル ① に書く値まで
  変わる（EDINET の原文を保持している面を書き換える）。正規化は D1 へ書く直前だけ。
- 未知の名称をそのまま書く: 上記のとおり公開面に語彙外の業種が出る。未知は None
  にし、呼び出し側が件数をログに出す。
"""

from __future__ import annotations

# 東証33業種（証券コード協議会の業種別分類。並びは業種コード順）。
# `証券、商品先物取引業` の区切りは読点で、EDINET も同じ表記だった（実測）。
TSE_SECTOR33_NAMES: tuple[str, ...] = (
    "水産・農林業",
    "鉱業",
    "建設業",
    "食料品",
    "繊維製品",
    "パルプ・紙",
    "化学",
    "医薬品",
    "石油・石炭製品",
    "ゴム製品",
    "ガラス・土石製品",
    "鉄鋼",
    "非鉄金属",
    "金属製品",
    "機械",
    "電気機器",
    "輸送用機器",
    "精密機器",
    "その他製品",
    "電気・ガス業",
    "陸運業",
    "海運業",
    "空運業",
    "倉庫・運輸関連業",
    "情報・通信業",
    "卸売業",
    "小売業",
    "銀行業",
    "証券、商品先物取引業",
    "保険業",
    "その他金融業",
    "不動産業",
    "サービス業",
)

_TSE_SECTOR33_SET = frozenset(TSE_SECTOR33_NAMES)

# EDINET の表記 → 東証の表記。実測で食い違ったのはこの 1 件だけ。
# 増やすときは実測の件数をコメントに残すこと（推測で足さない）。
EDINET_SECTOR_ALIASES: dict[str, str] = {
    "倉庫・運輸関連": "倉庫・運輸関連業",  # 34 社（2026-09-13 実測）
}


def normalize_sector33(raw: str | None) -> str | None:
    """EDINET「提出者業種」を東証33業種の名称へ揃える。33 名称以外は None。

    前後の空白を落とし、既知の表記ゆれだけを置き換える。`外国法人・組合` や
    空文字列、None は None を返す（推測で近い業種へ寄せない §3-1）。
    """
    if raw is None:
        return None
    text = str(raw).strip()
    text = EDINET_SECTOR_ALIASES.get(text, text)
    return text if text in _TSE_SECTOR33_SET else None


__all__ = ["EDINET_SECTOR_ALIASES", "TSE_SECTOR33_NAMES", "normalize_sector33"]
